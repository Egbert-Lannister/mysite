"""Build local Chinese webfonts from the official Noto Sans SC variable TTF.

Usage: python scripts/build_chinese_font.py path/to/NotoSansSC-variable.ttf
Build-only dependencies: fonttools, brotli. No network or database access.
"""
from pathlib import Path
import hashlib
import re
import sys

from fontTools import subset
from fontTools.ttLib import TTFont


def ranges(points):
    groups = []
    for point in sorted(points):
        if groups and point == groups[-1][1] + 1:
            groups[-1][1] = point
        else:
            groups.append([point, point])
    return ','.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in groups)


def build(source):
    root = Path(__file__).resolve().parents[1]
    destination = root / 'static/fonts/noto-sans-sc'
    destination.mkdir(parents=True, exist_ok=True)
    supported = set(TTFont(source).getBestCmap())
    catalog = (root / 'locale/zh_Hans/LC_MESSAGES/django.po').read_text(encoding='utf-8')
    core = {ord(c) for c in re.findall(r'[\u3000-\u9fff\uff00-\uffef]', catalog + '中')}
    common = set(range(0x3000, 0x3040)) | set(range(0xff00, 0xffef))
    for first in range(0xa1, 0xf8):
        for second in range(0xa1, 0xff):
            try:
                common.update(ord(c) for c in bytes([first, second]).decode('gb2312') if ord(c) >= 0x3000)
            except UnicodeDecodeError:
                pass
    css = ['/* Generated by scripts/build_chinese_font.py; see fonts/noto-sans-sc/OFL.txt. */']
    for name, points in [('ui', core & supported), ('common', (common - core) & supported)]:
        font = TTFont(source, recalcTimestamp=False)
        options = subset.Options()
        options.flavor = 'woff2'
        sub = subset.Subsetter(options=options)
        sub.populate(unicodes=points)
        sub.subset(font)
        font.flavor = 'woff2'
        output = destination / f'{name}.woff2'
        font.save(output)
        css.append('@font-face {\n  font-family: "TechBlog Chinese";\n'
                   f'  src: url("../fonts/noto-sans-sc/{name}.woff2") format("woff2");\n'
                   '  font-style: normal;\n  font-weight: 100 900;\n  font-display: swap;\n'
                   f'  unicode-range: {ranges(points)};\n}}')
        print(f'{name}: {len(points)} characters, {output.stat().st_size:,} bytes')
    (root / 'static/css/chinese-font.css').write_text('\n'.join(css) + '\n', encoding='utf-8')
    (destination / 'SOURCE.txt').write_text(
        'Noto Sans SC variable font, SIL Open Font License 1.1.\n'
        'Source: https://github.com/google/fonts/tree/main/ofl/notosanssc\n'
        f'Source TTF SHA-256: {hashlib.sha256(source.read_bytes()).hexdigest()}\n'
        'Subsets: current Chinese interface characters; remaining GB2312 Chinese characters and punctuation.\n'
        'Other glyphs use the platform fallback. Latin and code fonts are unchanged.\n'
        'Rebuild with scripts/build_chinese_font.py after updating the interface catalog.\n', encoding='utf-8')


if __name__ == '__main__':
    build(Path(sys.argv[1]))
